from enum import Enum
import unicodedata


def normalizar(value):
    value = getattr(value, 'value', value)
    return ''.join(c for c in unicodedata.normalize('NFD', str(value))
                   if unicodedata.category(c) != 'Mn').upper().replace(' ', '_')


